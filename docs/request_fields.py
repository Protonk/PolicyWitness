"""Project capacity field declarations into the Swift producer and Rust help reader."""
import hashlib
import json
from pathlib import Path
import re
import sys

import generator_common
import markdown_reader

sys.path.insert(0, str(Path(__file__).resolve().parent / 'contract'))
import tree as contract_tree

SWIFT = 'runner/Sources/PWRunnerCore/AdmissionField.swift'
RUST = 'controller/src/interface/admission_fields.rs'
LIMITS = 'docs/limits.json'
SURFACES = ('docs/contract/12-probes.surface.md', 'docs/contract/14-extensions.surface.md')
PLACEMENT = 'docs/contract/presentation.json'
INPUTS = (LIMITS, *SURFACES, PLACEMENT, 'docs/request_fields.py', 'docs/generator_common.py',
          'docs/contract/tree.py', 'docs/contract/record_definitions.py', 'docs/markdown_reader.py')


def plain(prose, limit, spans):
    def scalar(match):
        expected = f"limits.{limit['id']}.value_unit"
        value = generator_common.format_value(limit['value'], limit['unit'])
        if match[1] != expected or match[2] != value:
            raise ValueError(f'stale or mismatched help scalar {match[1]}, expected {expected}')
        spans.append(expected)
        return value
    doc = markdown_reader.parse(generator_common.SPAN_RE.sub(scalar, prose), 'request field help')
    if [t.type for t in doc.tokens] != ['paragraph_open', 'inline', 'paragraph_close']:
        raise ValueError('field help requires one complete paragraph per statement')
    children = doc.inlines[0].children
    if any(t.type not in {'text', 'code_inline', 'softbreak'} for t in children):
        raise ValueError('unsupported markup in field help')
    return ''.join(' ' if t.type == 'softbreak' else t.content for t in children)


def outputs(root):
    def read(name):
        return json.loads((root / name).read_text(), object_pairs_hook=generator_common.unique_object)
    data = read(LIMITS)
    owners = generator_common.validate_admission_fields(data)
    nodes = {n.id: n for path in SURFACES for n in contract_tree.parse_surface((root / path).read_text(), path)}
    homes = {node: document for document, regions in read(PLACEMENT)['documents'].items()
             for region in regions for node in region['nodes']}
    swift = ['// Generated by docs/generate_interface.py from the capacity field declarations.',
             'struct AdmissionField {', '    let spelling: String', '',
             '    private init(_ spelling: String) { self.spelling = spelling }', '']
    rust = ['// Generated by docs/generate_interface.py from the contract and capacity declarations.',
            'use super::field_help::{Admission, Entry};', '', '#[rustfmt::skip]',
            'pub static FIELDS: &[Admission] = &[']
    for ident, field in data['admission_fields'].items():
        pattern = field['pattern']
        slots = re.findall(r'\{(\w+)\}', pattern)
        args = ', '.join(f'_ {slot}: ' + ('String' if slot == 'role' else 'Int') for slot in slots)
        literal = re.sub(r'\{(\w+)\}', lambda m: r'\(' + m[1] + ')', pattern)
        if slots:
            swift.append(f'    static func {ident}({args}) -> AdmissionField {{ AdmissionField("{literal}") }}')
        else:
            swift.append(f'    static let {ident} = AdmissionField("{literal}")')
        aliases = ', '.join(json.dumps(alias) for alias in field.get('aliases', []))
        rust.append(f'    Admission {{ pattern: "{pattern}", aliases: &[{aliases}],')
        if 'statement' not in field:
            rust.append('        entry: None },')
            continue
        node = nodes[field['statement']]
        if node.kind != 'field' or homes.get(node.parent.id) != 'docs/REQUEST.md':
            raise ValueError(f'{ident}: field or placement missing')
        subject = node.parent.id
        limit, = owners[ident]
        key = generator_common.admission_key(field)
        spans = []
        paragraphs = [plain(node.prose, limit, spans)]
        if context := field.get('context'):
            if context != subject:
                raise ValueError(f'{ident}: unrelated field context')
            paragraphs.append(plain(nodes[context].prose, limit, spans))
        if len(spans) != 1:
            raise ValueError(f'{ident}: expected its applicable bound exactly once')
        body = ''.join('  '+line+'\n' for line in paragraphs)
        anchor = homes[subject]+'#'+contract_tree._anchor(node)
        rust += ['        entry: Some(Entry {',
                 f'            id: "{ident}", key: "{key}", node: "{node.id}", limit: "{limit["id"]}",',
                 f'            body: {json.dumps(body, ensure_ascii=False)},',
                 f'            destination: "{anchor}",', '        }) },']
    rust += ['];', '', '#[allow(dead_code)]', '#[rustfmt::skip]',
             'pub const SOURCE_DIGESTS: &[(&str, &str)] = &[']
    for path in sorted(INPUTS):
        digest = hashlib.sha256((root / path).read_bytes()).hexdigest()
        rust.append(f'    ("{path}", "{digest}"),')
    return {SWIFT: '\n'.join(swift+['}', '']), RUST: '\n'.join(rust+['];', ''])}
